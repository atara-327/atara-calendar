import { z } from 'zod';

// zod は、スキーマを作るとき（z.object など）に、new Function('') で、eval が使えるかを試す。
// 使えなければ、例外を握りつぶして、検証を速くする仕組み（JIT）をやめるだけで、動きは変わらない。
// しかし、握りつぶされる前に、CSP（script-src 'self'。設計書 10.3）の違反が、ブラウザに記録される。
// 'unsafe-eval' を CSP に足して黙らせるのは、XSS の被害を広げるので、しない。
// jitless にすると、試すこと自体をやめる。検証は少し遅くなるが、画面で検証するのは、1 回の依頼と、受け取った行だけで、
// 数千行でも問題にならない。
// スキーマを作る前に効かせる必要がある。main.tsx の、最初の import にすること。
// Worker には入れない。Worker には CSP がなく、eval が使えないときは、例外が握りつぶされるだけで、違反は記録されない。
z.config({ jitless: true });
